#include "libc.h"

int	ft_strisdigit(char *str)
{
	int	i;

	i = 0;
	if (str && (str[i] == '+' || str[i] == '-'))
		i++;
	while (str && str[i])
	{
		if (!(str[i] >= '0' && str[i] <= '9'))
			return (0);
		i++;
	}
	return (1);
}
